export const getEquipmentByCategory =
  (category) => {
    if (
      category === "all"
    ) {
      return equipment
    }

    return equipment.filter(
      (item) =>
        item.category ===
        category
    )
  }

export const getEquipmentByService =
  (serviceId) => {
    return equipment.filter(
      (item) =>
        item.relatedServices.includes(
          serviceId
        )
    )
  }